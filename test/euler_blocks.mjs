import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {build,runBlocks} from '../tools/euler-block-run.mjs';
import {artifactPaths,verifyEventFile,word} from '../tools/euler-2d-runtime.mjs';
import {run2DHostRecord} from '../tools/euler-2d-wasmtime-host.mjs';
import {writeDataset,checkDataset} from '../tools/euler-riemann-large.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
assert.equal(process.versions.node,'24.13.0');
const evidence=fs.mkdtempSync(path.join(root,'tmp/euler-block-test-'));
const record=runBlocks(26,path.join(evidence,'parallel'));
const checked=await verifyEventFile(record);
const serial=run2DHostRecord(...artifactPaths(),26,21,'riemann');
assert.deepEqual(fs.readFileSync(record),fs.readFileSync(serial.record),'serial and 24-process records');
const execution=JSON.parse(fs.readFileSync(path.join(evidence,'parallel/execution.json')));
assert.deepEqual(execution.physicalCalls,checked.final.calls);
assert.equal(fs.statSync(path.join(evidence,'parallel/step-00001/try-00/x/block-00.bin')).size,26*32);
const dataset=path.join(evidence,'dataset');await writeDataset(record,dataset);
assert.deepEqual((await checkDataset(dataset)).execution,execution);
console.log(`Unequal block sizes: all ${checked.steps} steps, frames, final words, and calls match the serial run`);

const {directory:cache,host:worker}=build(),reject=path.join(evidence,'rejected');fs.mkdirSync(reject);
execFileSync(worker,[cache,'x','26','0',path.join(evidence,'parallel/initial'),reject,word(100)],{stdio:'inherit'});
assert.equal(fs.readFileSync(path.join(reject,'block-00.meta')).readBigUInt64LE(),1n);
assert.ok(!fs.existsSync(path.join(reject,'block-00.bin')));
const missing=path.join(evidence,'missing');fs.mkdirSync(missing);
assert.throws(()=>execFileSync('bash',[path.join(root,'tools/euler-block-wave.sh'),worker,cache,'x','26',missing,missing,word(.01)],{stdio:'pipe'}),e=>e.status===1);
console.log('Rejected update preserves metadata; missing inputs fail the Bash wave');
console.log('Retained evidence: '+evidence);
