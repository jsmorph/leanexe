#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const {
  installProgramCache,
  normalizeExpandedProgram,
} = require("../tools/talos-lib");
const { makeTemporaryDirectory } = require("../tools/temp-directory");

const root = makeTemporaryDirectory("leanexe-talos-cache-");
const item = { name: "example", leanModule: "Example" };
const destination = path.join(root, "Project", "Example", "Program.lean");
const generated = path.join(root, "generated.lean");

const expanded = `/-
  AUTO-GENERATED by \`verifier emit\`. Do not edit by hand.
-/

import CodeLib.GeneratedCore

namespace Project.Example

def «module» : Wasm.Module := {}

-- Compile-time fidelity check: errors if WAT and generated Lean AST differ.
#guard_msgs (drop info) in
#eval Wasm.checkWatFidelity "../rust/build/example/program.wat" «module»

end Project.Example
`;
const normalizedExpanded = `/-
  AUTO-GENERATED by \`verifier emit\`. Do not edit by hand.
-/

import Project.TalosPrelude

namespace Project.Example

def «module» : Wasm.Module := {}

end Project.Example
`;

try {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, "def value := 1\n");
  fs.writeFileSync(generated, "def value := 1\n");
  installProgramCache(item, generated, "check", root);

  fs.writeFileSync(generated, "def value := 2\n");
  let rejected = false;
  try {
    installProgramCache(item, generated, "check", root);
  } catch (error) {
    if (!error.message.includes("differs from the tracked cache")) throw error;
    rejected = true;
  }
  if (!rejected) throw new Error("Talos cache check accepted different generated content");
  if (fs.readFileSync(destination, "utf8") !== "def value := 1\n") {
    throw new Error("Talos cache check changed the tracked cache");
  }
  installProgramCache(item, generated, "refresh", root);
  if (fs.readFileSync(destination, "utf8") !== "def value := 2\n") {
    throw new Error("Talos cache refresh did not install the generated cache");
  }

  const normalized = normalizeExpandedProgram(expanded, "example");
  if (normalized !== normalizedExpanded) {
    throw new Error(
      `expanded Talos cache normalization differed from the exact expected bytes: ${JSON.stringify(normalized)}`,
    );
  }
  const legacyExpanded = expanded.replace(
    "import CodeLib.GeneratedCore",
    "import CodeLib.Generated",
  );
  if (normalizeExpandedProgram(legacyExpanded, "example") !== normalizedExpanded) {
    throw new Error("legacy Talos generated import no longer normalizes");
  }
  for (const mutation of [
    expanded.replace("import CodeLib.GeneratedCore", "import CodeLib.GeneratedCoreExtra"),
    expanded.replace("../rust/build/example/program.wat", "../rust/build/other/program.wat"),
    expanded.replace("def «module»", "def func0 := watFunctionBody% \"x\" 0\n\ndef «module»"),
    expanded.replace("\nend Project.Example", `\n${expanded.match(/-- Compile-time[\s\S]*?«module»/)[0]}\n\nend Project.Example`),
  ]) {
    let rejected = false;
    try {
      normalizeExpandedProgram(mutation, "example");
    } catch (_error) {
      rejected = true;
    }
    if (!rejected) throw new Error("Talos cache normalization accepted a malformed guard");
  }
} finally {
  fs.rmSync(root, { recursive: true, force: true });
}

process.stdout.write("checked Talos cache comparison, refresh, and WAT-guard normalization\n");
