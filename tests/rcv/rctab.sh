#!/bin/sh
# Installs and runs RCTab, the ranked-choice tabulator of the Bright Spots Developers, at a pinned
# release, on a Linux x86-64 host.  The release's package bundles its Java runtime.  RCTab starts
# the JavaFX toolkit in its command-line mode as well, which needs an X display and GTK 3, so `run`
# starts a virtual display with xvfb-run when DISPLAY is unset (RCTab issue 789).
#
#   rctab.sh install DIR           downloads the release, checks its SHA-256, and unpacks it into
#                                  DIR/rcv, then removes the download
#   rctab.sh selftest DIR WORK     runs RCTab's own test contest 2015_portland_mayor in WORK and
#                                  compares its reports with the expected reports of the release's
#                                  source tree line by line, ignoring line terminators and the lines
#                                  that name the generating version or date, as RCTab's tests do
#   rctab.sh run DIR CONFIG OUT    tabulates the contest of CONFIG in the directory OUT, which then
#                                  holds RCTab's execution log, and copies the reports and the
#                                  console output into OUT
#   rctab.sh batch DIR LIST JOBS   runs `run` for each line `CONFIG OUT` of the file LIST, whose
#                                  paths are relative to LIST's directory, JOBS at a time, under one
#                                  virtual display when DISPLAY is unset
#
# RCTab exits with status 0 even when a tabulation fails, so `run` fails unless the console output
# begins with the pinned version, holds no SEVERE line, and names a results directory that holds
# each report.  RCTab's command-line mode tabulates one configuration per start.  The exit status is
# 0 on success and 1 otherwise, and `batch` fails when one of its runs fails.
set -eu

version=2.1.0
package=rctab_v2.1.0_Linux_X64.zip
package_sha256=46547b3be29d9c4cd807c261b977202af67a36cb7fc9248306bfd3a81ea06102
release=https://github.com/BrightSpots/rcv/releases/download/v$version
test_data=https://raw.githubusercontent.com/BrightSpots/rcv/v$version/src/test/resources/network/brightspots/rcv/test_data
selftest_files="
3dd1b5ad6dfd17f56c7b558b9897272e675eceedac15773ac1fcdb06d2b16928 2015_portland_mayor_config.json
3edd551aea568928af25477f105cbd4b2d843233a5d4f6f5239d664545b746ef 2015_portland_mayor_cvr.xlsx
d314782dce95f98826f7b09df21ad75905b68545067726acd09946dded9e8105 2015_portland_mayor_expected_detailed_report.csv
7517b5180fb40e4d379c816c77178c900d14bd5c9c8445143a653269fe57501d 2015_portland_mayor_expected_detailed_report.json
"
reports="summary_report.csv detailed_report.csv detailed_report.json"

fail() {
  echo "rctab.sh: $*" >&2
  exit 1
}

fetch() {
  curl -sSfL -o "$3" "$1" || fail "cannot download $1"
  echo "$2  $3" | sha256sum -c --status - || fail "$3: SHA-256 $(sha256sum "$3" | cut -d' ' -f1), expected $2"
}

install() {
  dir=$1
  [ ! -e "$dir/rcv" ] || fail "$dir/rcv exists"
  mkdir -p "$dir/download"
  fetch "$release/$package" "$package_sha256" "$dir/download/$package"
  unzip -q "$dir/download/$package" -d "$dir"
  rm -r "$dir/download"
  echo "installed RCTab $version in $dir/rcv"
}

run() {
  dir=$(cd "$1" && pwd)
  config=$(cd "$(dirname "$2")" && pwd)/$(basename "$2")
  mkdir -p "$3"
  out=$(cd "$3" && pwd)
  console=$out/console.txt
  set -- "$dir/rcv/bin/RCTab" --cli "$config" --name leanexe
  [ -n "${DISPLAY:-}" ] || set -- xvfb-run -a "$@"
  (cd "$out" && "$@") > "$console" 2>&1 || fail "RCTab exited with status $?, output in $console"
  [ "$(head -n 1 "$console")" = "RCTab version $version" ] || fail "$console does not begin with RCTab version $version"
  ! grep -q SEVERE "$console" || fail "$console holds SEVERE lines"
  results=$(sed -n 's/.*Results written to: //p' "$console")
  [ -n "$results" ] && [ -d "$results" ] || fail "$console names no results directory"
  for r in $reports; do
    set -- "$results"/*_"$r"
    [ $# -eq 1 ] && [ -f "$1" ] || fail "no single $r in $results"
    cp -f "$1" "$out/$r"
  done
}

batch() {
  [ -n "${DISPLAY:-}" ] || exec xvfb-run -a sh "$0" batch "$@"
  dir=$(cd "$1" && pwd)
  script=$(cd "$(dirname "$0")" && pwd)/$(basename "$0")
  cd "$(dirname "$2")"
  xargs -L 1 -P "$3" sh "$script" run "$dir" < "$(basename "$2")" || fail "a run of $2 failed"
}

selftest() {
  dir=$1 work=$2
  contest=$work/2015_portland_mayor
  mkdir -p "$contest"
  echo "$selftest_files" | while read -r sha name; do
    [ -n "$name" ] || continue
    fetch "$test_data/2015_portland_mayor/$name" "$sha" "$contest/$name"
  done
  run "$dir" "$contest/2015_portland_mayor_config.json" "$work/out"
  for r in detailed_report.csv detailed_report.json; do
    tr -d '\r' < "$contest/2015_portland_mayor_expected_$r" | grep -v -e 'Generated By' -e GeneratedDate -e generatedBy > "$work/expected-$r"
    tr -d '\r' < "$work/out/$r" | grep -v -e 'Generated By' -e GeneratedDate -e generatedBy > "$work/actual-$r"
    cmp -s "$work/expected-$r" "$work/actual-$r" || fail "$r differs from the expected report: diff $work/expected-$r $work/actual-$r"
    echo "2015_portland_mayor $r equals the expected report"
  done
}

case ${1:-} in
  install) [ $# -eq 2 ] || fail "usage: rctab.sh install DIR"; install "$2" ;;
  selftest) [ $# -eq 3 ] || fail "usage: rctab.sh selftest DIR WORK"; selftest "$2" "$3" ;;
  run) [ $# -eq 4 ] || fail "usage: rctab.sh run DIR CONFIG OUT"; run "$2" "$3" "$4" ;;
  batch) [ $# -eq 4 ] || fail "usage: rctab.sh batch DIR LIST JOBS"; batch "$2" "$3" "$4" ;;
  *) fail "usage: rctab.sh install DIR | selftest DIR WORK | run DIR CONFIG OUT | batch DIR LIST JOBS" ;;
esac
